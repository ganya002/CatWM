def swift_type(text):
    base, array, optional = parse_type(text)
    out = SWIFT_BASE[base]
    if array:
        out = f"[{out}]"
    return f"{out}?" if optional else out


def swift_name(name):
    if name[:1].isdigit():
        return "_" + name
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def swift_arg_type(arg):
    if arg["type"] == "enum":
        return arg["enum"]
    return {"string": "String", "int": "Int", "number": "Double", "bool": "Bool", "string[]": "[String]"}[arg["type"]]


def swift_value(arg):
    local = swift_name(camel(arg["name"]))
    return f"{local}.rawValue" if arg["type"] == "enum" else local


def swift_struct(name, fields):
    out = ["", f"public struct {name}: Codable, Equatable, Sendable {{"]
    out += [f"    public let {swift_name(field['name'])}: {swift_type(field['type'])}" for field in fields]
    out.append("}")
    return out


def swift_client(schema, enums):
    out = [f"// {NOTICE}", "", "import Foundation", "", f"public let protocolVersion = {schema['protocol']}"]
    for choices, name in enums.by_choices.items():
        out += ["", f"public enum {name}: String, CaseIterable, Sendable {{"]
        out += [f"    case {swift_name(camel(choice))} = {json.dumps(choice)}" for choice in choices]
        out.append("}")
    out += swift_struct("Rect", [{"name": n, "type": "number"} for n in ("x", "y", "width", "height")])
    for command in schema["commands"]:
        kind, name, fields = result_info(command)
        if name:
            out += swift_struct(name, fields)
    cases = []
    for event in schema["events"]:
        name = event_type(event["name"])
        out += swift_struct(name + "Data", event["data"])
        cases.append((event["name"], camel(name), name + "Data"))
    out += ["", "public enum Event: Sendable {"]
    out += [f"    case {case}({data})" for _, case, data in cases]
    out += ["    case unknown(name: String, data: JSONValue)", "", "    static func decode(name: String, data: Data) throws -> Event {",
            "        switch name {"]
    for event, case, data in cases:
        out += [f"        case {json.dumps(event)}: return .{case}(try JSONDecoder().decode({data}.self, from: data))"]
    out += ["        default: return .unknown(name: name, data: try JSONDecoder().decode(JSONValue.self, from: data))",
            "        }", "    }", "}", "", SWIFT_TRANSPORT]
    for command in schema["commands"]:
        kind, name, fields = result_info(command)
        returns = {"none": "", "text": " -> String", "value": " -> JSONValue", "object": f" -> {name}",
                   "list": f" -> [{name}]"}[kind]
        args = sorted(command["args"], key=lambda arg: not arg["required"])
        params = ", ".join(f"{swift_name(camel(arg['name']))}: {swift_arg_type(arg)}"
                           + ("" if arg["required"] else "? = nil") for arg in args)
        out += ["", f"    /// {command['summary']}",
                f"    public func {swift_name(camel(command['name']))}({params}) throws{returns} {{",
                f"        {'var' if args else 'let'} args: [String: Any] = [:]"]
        for arg in args:
            local = swift_name(camel(arg["name"]))
            value = "value" if not arg["required"] else local
            if arg["type"] == "enum":
                value += ".rawValue"
            if arg["required"]:
                out.append(f"        args[{json.dumps(arg['name'])}] = {value}")
            else:
                out.append(f"        if let value = {local} {{ args[{json.dumps(arg['name'])}] = {value} }}")
        call = f"try call({json.dumps(command['name'])}, args)"
        if kind == "none":
            out.append(f"        _ = {call}")
        elif kind == "text":
            out.append(f"        return try decode(String.self, {call})")
        elif kind == "value":
            out.append(f"        return try decode(JSONValue.self, {call})")
        elif kind == "object":
            out.append(f"        return try decode({name}.self, {call})")
        else:
            out.append(f"        return try decode([{name}].self, {call})")
        out.append("    }")
    out += ["}", ""]
    return "\n".join(out)


